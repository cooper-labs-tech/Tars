#!/usr/bin/env node
// The environment variables Hermes Agent reads to find a provider of its own, from its source (27/11). A Hermes agent
// of Tars talks to the endpoint Tars gives it and to nothing else, so its line takes each of these out
// (providers/hermes-provider.ts), the way ANTHROPIC_API_KEY is blanked for every alternative provider.
//
// Read where Hermes declares them, never listed by hand:
// - hermes_cli/auth.py, _REGISTRY_ROWS: each API-key row's api_key_env_vars (the 4th item of a tuple row);
// - providers/*.py and plugins/model-providers/*/__init__.py: each ProviderProfile's env_vars and extra_env_vars;
// - hermes_cli/providers.py: the overlays' extra_env_vars;
// - agent/bedrock_adapter.py, _AWS_AUTH_ENV_CHAIN: the AWS credential variables.
// Checked once against Hermes 0.23.4's own runtime registry (the same 75 names).
//
// usage: node scripts/hermes-provider-keys.mjs <hermes checkout>         prints the names as JSON
//        node scripts/hermes-provider-keys.mjs <hermes checkout> --write writes electron/providers/hermes-provider-keys.ts
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const NAME = /"([A-Z][A-Z0-9_]*)"/g;
const namesIn = (text) => [...text.matchAll(NAME)].map(m => m[1]);

/** The tuples a keyword argument holds, `kw=( ... )`, each tuple's quoted names. */
function keywordTuples(text, keyword) {
  const out = [];
  const re = new RegExp(`\\b${keyword}\\s*=\\s*\\(([^)]*)\\)`, 'g');
  for (const m of text.matchAll(re)) out.push(...namesIn(m[1]));
  return out;
}

/** auth.py's API-key rows: `("id", "Name", <base url>, ("KEY", ...), ...)`, the first tuple of names in each row. */
function registryRowKeys(text) {
  const start = text.indexOf('_REGISTRY_ROWS');
  const end = text.indexOf('PROVIDER_REGISTRY', start + 1);
  if (start < 0 || end < 0) throw new Error('hermes_cli/auth.py: _REGISTRY_ROWS not found');
  const rows = text.slice(start, end);
  const out = [];
  for (const m of rows.matchAll(/\(\s*"[a-z0-9-]+",\s*"[^"]*",[^()]*?\(([^()]*)\)/g)) out.push(...namesIn(m[1]));
  out.push(...keywordTuples(rows, 'api_key_env_vars'));
  return out;
}

/** The AWS chain: `_AWS_AUTH_ENV_CHAIN: ... = ( ("A",), ("B", "C"), ... )`. */
function awsChain(text) {
  const m = /_AWS_AUTH_ENV_CHAIN[^=]*=\s*\(([\s\S]*?)\n\)/.exec(text);
  if (!m) throw new Error('agent/bedrock_adapter.py: _AWS_AUTH_ENV_CHAIN not found');
  return namesIn(m[1].replace(/#.*$/gm, ''));
}

export function hermesProviderKeys(checkout) {
  const read = (p) => fs.readFileSync(path.join(checkout, p), 'utf8');
  const names = new Set([
    ...registryRowKeys(read('hermes_cli/auth.py')),
    ...keywordTuples(read('hermes_cli/providers.py'), 'extra_env_vars'),
    ...awsChain(read('agent/bedrock_adapter.py')),
  ]);
  const profileFiles = [
    ...fs.readdirSync(path.join(checkout, 'providers')).filter(f => f.endsWith('.py')).map(f => path.join('providers', f)),
    ...fs.readdirSync(path.join(checkout, 'plugins', 'model-providers'), { withFileTypes: true }).filter(d => d.isDirectory())
      .map(d => path.join('plugins', 'model-providers', d.name, '__init__.py')).filter(f => fs.existsSync(path.join(checkout, f))),
  ];
  for (const f of profileFiles) {
    const text = read(f);
    for (const kw of ['env_vars', 'extra_env_vars']) for (const n of keywordTuples(text, kw)) names.add(n);
  }
  return [...names].sort();
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const checkout = process.argv[2];
  if (!checkout) { console.error('usage: node scripts/hermes-provider-keys.mjs <hermes checkout> [--write]'); process.exit(2); }
  const names = hermesProviderKeys(checkout);
  if (!process.argv.includes('--write')) { console.log(JSON.stringify({ count: names.length, names })); process.exit(0); }
  // The checkout's tag (its pyproject.toml holds a placeholder version), and its commit.
  const version = (() => {
    try { return execFileSync('git', ['-C', checkout, 'describe', '--tags', '--long'], { encoding: 'utf8' }).trim(); } catch { return 'an untagged checkout'; }
  })();
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'electron', 'providers', 'hermes-provider-keys.ts');
  fs.writeFileSync(out, `// Generated by scripts/hermes-provider-keys.mjs from Hermes Agent ${version}: the variables it reads to find a provider\n`
    + '// of its own (hermes_cli/auth.py _REGISTRY_ROWS, the provider profiles\' env_vars, hermes_cli/providers.py, the AWS\n'
    + '// chain of agent/bedrock_adapter.py). Regenerate it, never edit it: hermes-provider.test.ts checks it against a checkout.\n'
    + `export const HERMES_PROVIDER_KEYS: readonly string[] = [\n${names.map(n => `  '${n}',`).join('\n')}\n];\n`);
  console.log(`wrote ${names.length} names to ${out}`);
}
